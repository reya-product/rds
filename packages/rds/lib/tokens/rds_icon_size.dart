/// RDS icon size scale.
///
/// Pass these values to the [size] parameter of [Icon].
abstract final class RdsIconSize {
  /// 12px — micro decorations (e.g. badge dot, inline indicator).
  static const double xs = 12;

  /// 16px — inline icons in dense text, small button icons.
  static const double sm = 16;

  /// 20px — standard button icon, form field leading/trailing icon.
  static const double md = 20;

  /// 24px — navigation icons, standalone action icons.
  static const double lg = 24;

  /// 32px — large decorative icons, empty-state illustrations.
  static const double xl = 32;
}
